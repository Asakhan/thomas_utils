"""한국어 AI 티(AI-tell) 패턴 정의.

`im-not-ai` (https://github.com/epoko77-ai/im-not-ai) 의 taxonomy v2.0 을 기반으로
정규식으로 탐지 가능한 패턴 40여 종을 정의한다. (A/B/C/D/E/F/G/H/I/J 10개 카테고리)

심각도:
- S1: 단 한 번 등장으로도 AI 작성 신호 — 무조건 제거 대상
- S2: 1~2회는 허용, 3회 이상이면 제거 대상
- S3: 다른 패턴과 겹칠 때만 문제

각 항목은 `Pattern` 데이터클래스로 표현된다. `regex` 가 None 이면
LLM 윤문 단계에서만 다루는 카테고리(예: 문장 길이 분산, 문단 길이 균일)이다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Iterable, List, Optional, Pattern as RePattern, Tuple


# ---------------------------------------------------------------------------
# 데이터클래스
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Pattern:
    code: str            # "A-1", "C-11" ...
    name: str
    severity: str        # "S1" | "S2" | "S3"
    category: str        # "A" ~ "J"
    description: str
    regex: Optional[RePattern[str]] = None
    advice: str = ""     # 윤문 시 가이드


@dataclass
class Detection:
    code: str
    name: str
    severity: str
    category: str
    span: Tuple[int, int]
    snippet: str
    advice: str = ""


def _re(pattern: str, flags: int = 0) -> RePattern[str]:
    return re.compile(pattern, flags)


